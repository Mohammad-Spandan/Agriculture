CREATE TABLE Soil_Types (
    soil_type_id INT PRIMARY KEY,
    soil_type_name VARCHAR(100) NOT NULL UNIQUE
);

-- Agro-Ecological Zones (AEZ)
CREATE TABLE Agro_Ecological_Zones (
    aez_id INT PRIMARY KEY,
    zone_name VARCHAR(150) NOT NULL,
    area_sqkm DECIMAL(10, 2) NOT NULL,
    soil_type_id INT NOT NULL,
    sand_pct DECIMAL(5, 2),
    alluvium_pct DECIMAL(5, 2),
    clay_pct DECIMAL(5, 2),
    CONSTRAINT fk_aez_soil FOREIGN KEY (soil_type_id) REFERENCES Soil_Types(soil_type_id)
);

-- Administrative District Dimension
CREATE TABLE Districts (
    district_id INT PRIMARY KEY,
    district_name VARCHAR(100) NOT NULL UNIQUE
);

-- District Forest Land Acreages
CREATE TABLE Forest_Lands (
    forest_record_id INT PRIMARY KEY,
    district_id INT NOT NULL,
    reserved_ac DECIMAL(12, 2) DEFAULT 0.00,
    prot_sec20_ac DECIMAL(12, 2) DEFAULT 0.00,
    prot_sec4_6_ac DECIMAL(12, 2) DEFAULT 0.00,
    acquired_ac DECIMAL(12, 2) DEFAULT 0.00,
    unclass_fd_ac DECIMAL(12, 2) DEFAULT 0.00,
    total_fd_ac DECIMAL(12, 2) DEFAULT 0.00,
    unclass_da_ac DECIMAL(12, 2) DEFAULT 0.00,
    grand_total_ac DECIMAL(12, 2) DEFAULT 0.00,
    CONSTRAINT fk_forest_district FOREIGN KEY (district_id) REFERENCES Districts(district_id)
);

-- National Agricultural Land Utilization Time Series ('000 Acres)
CREATE TABLE Land_Utilization (
    fiscal_year VARCHAR(10) PRIMARY KEY,
    forest_000ac DECIMAL(10, 2) NOT NULL,
    not_available_000ac DECIMAL(10, 2) NOT NULL,
    cultiv_waste_000ac DECIMAL(10, 2) NOT NULL,
    curr_fallows_000ac DECIMAL(10, 2) NOT NULL,
    net_cropped_000ac DECIMAL(10, 2) NOT NULL,
    sown_more_once_000ac DECIMAL(10, 2) NOT NULL,
    total_cropped_000ac DECIMAL(10, 2) NOT NULL
);

-- National Macro GDP by Broad Sector (Million BDT & Share %)
CREATE TABLE GDP_By_Sector (
    fiscal_year VARCHAR(10) PRIMARY KEY,
    agriculture_gva_mtk DECIMAL(14, 2) NOT NULL,
    industry_gva_mtk DECIMAL(14, 2) NOT NULL,
    service_gva_mtk DECIMAL(14, 2) NOT NULL,
    total_gva_mtk DECIMAL(14, 2) NOT NULL,
    agriculture_share_pct DECIMAL(5, 2) NOT NULL,
    industry_share_pct DECIMAL(5, 2) NOT NULL,
    service_share_pct DECIMAL(5, 2) NOT NULL,
    total_share_pct DECIMAL(5, 2) NOT NULL
);

-- Detailed Agricultural Subsectors GVA (Million BDT & Share %)
CREATE TABLE Agriculture_Subsector_GVA (
    fiscal_year VARCHAR(10) PRIMARY KEY,
    agriculture_gva_million_tk DECIMAL(14, 2) NOT NULL,
    crops_horticulture_gva DECIMAL(14, 2) NOT NULL,
    animal_farming_gva DECIMAL(14, 2) NOT NULL,
    forest_services_gva DECIMAL(14, 2) NOT NULL,
    fishing_gva DECIMAL(14, 2) NOT NULL,
    agriculture_share_pct DECIMAL(5, 2) NOT NULL,
    crops_horticulture_share_pct DECIMAL(5, 2) NOT NULL,
    animal_farming_share_pct DECIMAL(5, 2) NOT NULL,
    forest_services_share_pct DECIMAL(5, 2) NOT NULL,
    fishing_share_pct DECIMAL(5, 2) NOT NULL
);

-- District & Regional Agricultural Census Holdings
CREATE TABLE Agricultural_Holdings (
    holding_id INT PRIMARY KEY,
    division_name VARCHAR(50) NOT NULL,
    area_type VARCHAR(20) NOT NULL,
    district_code VARCHAR(10),
    district_name VARCHAR(100),
    all_holdings DECIMAL(14, 2),
    non_farm_holdings DECIMAL(14, 2),
    total_farm_holdings DECIMAL(14, 2),
    small_farm_holdings DECIMAL(14, 2),
    medium_farm_holdings DECIMAL(14, 2),
    large_farm_holdings DECIMAL(14, 2),
    owner_holdings DECIMAL(14, 2),
    owner_cum_tenant_holdings DECIMAL(14, 2),
    tenant_holdings DECIMAL(14, 2),
    agriculture_labour_holdings DECIMAL(14, 2),
    fisheries_holdings DECIMAL(14, 2)
);

-- District Annual Rainfall and Volume Statistics (64 Districts)
CREATE TABLE District_Rainfall (
    rainfall_record_id INT PRIMARY KEY,
    district_name VARCHAR(100) NOT NULL,
    district_area_km2 DECIMAL(10, 2) NOT NULL,
    annual_avg_rainfall_2017_mm DECIMAL(10, 2),
    annual_avg_rainfall_2018_mm DECIMAL(10, 2),
    rainfall_volume_2017_million_m3 DECIMAL(12, 2),
    rainfall_volume_2018_million_m3 DECIMAL(12, 2)
);

-- Meteorological Rainfall Stations Network (243 Stations)
CREATE TABLE Rainfall_Stations (
    station_record_id INT PRIMARY KEY,
    district_name VARCHAR(100) NOT NULL,
    station_name VARCHAR(100) NOT NULL,
    station_id VARCHAR(50) NOT NULL
);

-- Meteorological Station Monthly Temperature Observations (370 Records)
CREATE TABLE Temperature_Observations (
    temp_record_id INT PRIMARY KEY,
    page_source INT NOT NULL,
    station_name VARCHAR(100) NOT NULL,
    jan DECIMAL(5, 2),
    feb DECIMAL(5, 2),
    mar DECIMAL(5, 2),
    apr DECIMAL(5, 2),
    may DECIMAL(5, 2),
    jun DECIMAL(5, 2),
    jul DECIMAL(5, 2),
    aug DECIMAL(5, 2),
    sep DECIMAL(5, 2),
    oct DECIMAL(5, 2),
    nov DECIMAL(5, 2),
    december  DECIMAL(5, 2)
);

